/* ==========================================================================
   Jasnota — libraries: filters, search, sorting (articles, glossary, myths,
   sources, map). Markup contract (generated by tools/build.mjs):
     [data-lib]                      one library
       .filter[data-filter="name"]   a group of buttons, each with data-value ("" = all)
       [data-search]                 optional search input
       [data-item]                   items: data-<name>="v1 v2", data-text="…" (search haystack)
       [data-group]                  optional sections, hidden when they have no visible item
       [data-letters]                optional: items carry data-letter-mk / -en; the first of each letter
                                     shows its letter; with [data-sortable] items re-sort per language
       .lib__status / .lib__empty    live count and the empty state
   State lives in the URL (?pillar=2&format=myth&q=…), so a filtered view can be shared.
   Everything is visible without JS.
   ========================================================================== */
(() => {
  'use strict';
  const J = window.Jasnota || null;
  const $$ = (s, c = document) => Array.from(c.querySelectorAll(s));
  const t = (k) => (J ? J.t(k) : k);
  const lang = () => (J ? J.lang : document.documentElement.lang);
  const MOTION = !!(J && J.MOTION);
  const E_OUT = 'cubic-bezier(0.16, 1, 0.3, 1)';
  const norm = (s) => String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[„“”"'’‘]/g, '');

  $$('[data-lib]').forEach((lib) => {
    const items = $$('[data-item]', lib);
    if (!items.length) return;
    const groups = $$('.filter[data-filter]', lib);
    const search = lib.querySelector('[data-search]');
    const status = lib.querySelector('.lib__status');
    const empty = lib.querySelector('.lib__empty');
    const sections = $$('[data-group]', lib);
    const letters = lib.querySelector('[data-letters]');
    const sortable = lib.hasAttribute('data-sortable');
    const state = {};
    items.forEach((it) => { it._t = norm(it.dataset.text || it.textContent); });

    function markLetters() {
      if (!letters) return;
      const key = lang() === 'en' ? 'letterEn' : 'letterMk';
      const seen = new Set();
      $$('[data-item]', letters).forEach((it) => {
        const L = it.dataset[key] || '';
        const first = !it.hidden && !seen.has(L);
        if (first) seen.add(L);
        it.classList.toggle('is-first', first);
        const el = it.querySelector('.term__letter');
        if (el && el.textContent !== L) el.textContent = L;
      });
    }

    function sort() {
      if (!sortable || !letters) return;
      const key = lang() === 'en' ? 'sortEn' : 'sortMk';
      items.slice().sort((a, b) => +a.dataset[key] - +b.dataset[key]).forEach((it) => letters.appendChild(it));
    }

    function syncURL() {
      const u = new URL(location.href);
      groups.forEach((g) => { const n = g.dataset.filter; if (state[n]) u.searchParams.set(n, state[n]); else u.searchParams.delete(n); });
      if (search) { const q = search.value.trim(); if (q) u.searchParams.set('q', q); else u.searchParams.delete('q'); }
      history.replaceState(null, '', u.pathname + u.search.replace(/static=(&|$)/, 'static$1') + u.hash);
    }

    function apply(animate) {
      const words = search ? norm(search.value.trim()).split(/\s+/).filter(Boolean) : [];
      let n = 0;
      const show = [];
      items.forEach((it) => {
        const ok = groups.every((g) => { const v = state[g.dataset.filter]; return !v || (it.dataset[g.dataset.filter] || '').split(' ').includes(v); })
          && words.every((w) => it._t.includes(w));
        if (ok) { n++; if (it.hidden) show.push(it); }
        it.hidden = !ok;
      });
      sections.forEach((s) => { s.hidden = !s.querySelector('[data-item]:not([hidden])'); });
      const filtered = n !== items.length;
      if (status) status.textContent = filtered ? t('lib_count').replace('{n}', n).replace('{total}', items.length) : '';
      if (empty) { empty.hidden = n > 0; empty.textContent = n ? '' : t('lib_empty'); }
      markLetters();
      if (animate && MOTION) {
        show.slice(0, 14).forEach((it, i) => it.animate(
          [{ opacity: 0, transform: 'translate3d(0, 12px, 0)' }, { opacity: 1, transform: 'none' }],
          { duration: 600, delay: i * 40, easing: E_OUT, fill: 'backwards' }));
      }
      if (J) J.refresh();
    }

    groups.forEach((g) => {
      const btns = $$('button[data-value]', g);
      const set = (v) => { state[g.dataset.filter] = v; btns.forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.value === v))); };
      g._set = set;
      btns.forEach((b) => b.addEventListener('click', () => { set(b.dataset.value); apply(true); syncURL(); }));
    });
    if (search) {
      let timer = 0;
      search.addEventListener('input', () => { clearTimeout(timer); timer = setTimeout(() => { apply(false); syncURL(); }, 110); });
      search.addEventListener('keydown', (e) => { if (e.key === 'Escape' && search.value) { search.value = ''; apply(false); syncURL(); } });
    }

    // initial state from the URL
    const params = new URLSearchParams(location.search);
    groups.forEach((g) => {
      const v = params.get(g.dataset.filter);
      if (v && $$('button[data-value]', g).some((b) => b.dataset.value === v)) g._set(v); else g._set('');
    });
    if (search && params.get('q')) search.value = params.get('q');
    sort();
    apply(false);

    // a link to an item hidden by a filter clears the filters first
    const reveal = () => {
      const id = decodeURIComponent(location.hash.slice(1));
      const el = id && document.getElementById(id);
      const item = el && el.closest('[data-item]');
      if (!item || !item.hidden) return;
      groups.forEach((g) => g._set(''));
      if (search) search.value = '';
      apply(false); syncURL();
      requestAnimationFrame(() => el.scrollIntoView({ block: 'start' }));
    };
    reveal();
    window.addEventListener('hashchange', reveal);
    document.addEventListener('click', (e) => {
      const a = e.target.closest('a[href^="#"]');
      if (!a) return;
      const el = document.getElementById(decodeURIComponent(a.hash.slice(1)));
      const item = el && el.closest('[data-item]');
      if (item && item.hidden) { groups.forEach((g) => g._set('')); if (search) search.value = ''; apply(false); syncURL(); }
    }, true);

    if (J) J.onLang(() => { sort(); apply(false); });
  });
})();
