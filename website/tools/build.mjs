function finish(file, html) {
  const rel = relative(SITE, dirname(file));
  const depth = rel.split(/[\\/]/).filter(Boolean).length;
  const r = '../'.repeat(depth);
  const page = (html.match(/<body[^>]*data-page="([^"]+)"/) || [])[1] || '';
  const path = rel ? rel.split(/[\\/]/).join('/') + '/' : '';
  const is404 = file.endsWith('404.html');
  const home = page === 'home';
  for (const [name, content] of [
    ['shell:head', shell.head(r, { gsap: home, path: is404 ? '404.html' : path, index: !is404, og: OG.get(is404 ? '' : path) || OG.get('') })],
    ['shell:top', shell.top(r, page)],
    ['shell:foot', shell.foot(r, { gsap: home, letter: !(home || page === 'contact') })],
  ]) {
    const next = shell.inject(html, name, content);
    if (next === null) throw new Error(`${relative(SITE, file)}: missing <!-- ${name} --> marker`);
    html = next;
  }
  return html;
}
const written = [];
function writePage(path, html, { sitemap = true, date } = {}) {
  const file = join(SITE, path, 'index.html');
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, finish(file, html));
  if (sitemap) written.push({ path, date });
  log('wrote', relative(SITE, file));
}

