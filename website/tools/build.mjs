const PHOTO_MAX = 2000;
function syncPhotos() {
  const out = join(SITE, 'assets', 'photos');
  const src = existsSync(PHOTOS) ? readdirSync(PHOTOS) : [];
  if (existsSync(PHOTOS)) {   // the Instagram pages read this list so they never probe for missing files
    const all = {};
    for (const n of src) { const m = n.match(/^([a-z0-9-]+)\.(jpe?g|png)$/i); if (m) all[m[1].toLowerCase()] = n; }
    writeFileSync(join(PHOTOS, 'manifest.json'), JSON.stringify(all, null, 2) + '\n');
  }
  let found = null;
  const f = src.find((n) => /^portrait\.(jpe?g|png)$/i.test(n));
  if (f) {
    const ext = f.split('.').pop().toLowerCase().replace('jpeg', 'jpg');
    mkdirSync(out, { recursive: true });
    const from = join(PHOTOS, f), to = join(out, `portrait.${ext}`);
    let resized = false;
    if (statSync(from).size > 900 * 1024) {
      try { execFileSync('sips', ['-Z', String(PHOTO_MAX), ...(ext === 'jpg' ? ['-s', 'formatOptions', '82'] : []), from, '--out', to], { stdio: 'ignore' }); resized = true; } catch { /* copy as is */ }
    }
    if (!resized) copyFileSync(from, to);
    found = `portrait.${ext}`;
  }
  if (existsSync(out)) {
    for (const n of readdirSync(out)) if (n !== found) rmSync(join(out, n));
    if (!readdirSync(out).length) rmSync(out, { recursive: true });
  }
  log(found ? `photo → assets/photos/${found}` : 'photo: no portrait yet, the placeholder stays');
  return found;
}
