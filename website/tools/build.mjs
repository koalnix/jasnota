function load() {
  const sources = read(join(CONTENT, 'sources.json'));
  const concepts = read(join(CONTENT, 'concepts.json'));
  const myths = read(join(CONTENT, 'myths.json'));
  const calendar = read(join(CONTENT, 'calendar.json'));
  const map = read(join(CONTENT, 'map.json'));
  const S = new Map(sources.map((s) => [s.id, s]));
  for (const s of sources) Object.assign(s, parseAPA(s));
  const articles = readdirSync(join(CONTENT, 'articles')).filter((f) => f.endsWith('.json')).sort().map((f) => {
    const a = read(join(CONTENT, 'articles', f));
    for (const k of ['slug', 'pillar', 'format', 'date', 'title', 'dek', 'reading_min', 'body', 'references']) if (a[k] == null) throw new Error(`${f}: missing "${k}"`);
    if (!FORMATS[a.format]) throw new Error(`${f}: unknown format "${a.format}"`);
    for (const id of a.references) if (!S.has(id)) throw new Error(`${f}: reference "${id}" is not in sources.json`);
    a.file = f;
    a.cal = calendar.find((c) => c.article && c.article.endsWith(f)) || null;
    a.title_en = (a.en && a.en.title) || (a.cal && a.cal.title_en) || '';
    return a;
  }).sort((x, y) => x.date.localeCompare(y.date));
  for (const c of [...concepts, ...myths]) for (const id of c.source_ids) if (!S.has(id)) throw new Error(`unknown source "${id}"`);
  const slugs = new Set();
  for (const a of articles) { if (slugs.has(a.slug)) throw new Error('duplicate slug ' + a.slug); slugs.add(a.slug); }
  // weekly calendar items without a published piece yet
  const upcoming = calendar.filter((c) => !(c.article && articles.some((a) => c.article.endsWith(a.file))));
  log(`${articles.length} articles · ${upcoming.length} upcoming · ${sources.length} sources · ${concepts.length} concepts · ${myths.length} myths · ${map.entries.length} map entries`);
  return { sources, S, concepts, myths, calendar, upcoming, articles, map };
}

/* APA author-date → names + year, for "(Kenny, 2011)" style citations */
function parseAPA(s) {
  const m = s.apa.match(/^(.*?)\s\((\d{4})[a-z]?(?:,[^)]*)?\)\./);
  if (!m) return { names: [], year: '', cite: s.id, title: s.apa };
  const names = [...m[1].matchAll(/(?:^|,\s*(?:&\s*)?|&\s*|…\s*)([^,&…]+?),\s*(?:[A-ZÀ-ŽА-Я][a-zа-я]?\.(?:\s?-?\s?[A-ZÀ-ŽА-Я][a-zа-я]?\.)*)/g)].map((x) => x[1].trim());
  const who = names.length > 2 ? `${names[0]} et al.` : names.join(' & ');
  const rest = s.apa.slice(m[0].length).trim();
  const text = rest.replace(/\s*https?:\/\/\S+\s*$/, '');
  return { names, year: m[2], cite: `${who}, ${m[2]}`, citeN: `${who} (${m[2]})`, title: text.split(/\.\s/)[0] };
}
const apaText = (s) => esc(s.apa.replace(/\s*https?:\/\/\S+\s*$/, ''));

/* In-text citations stay as (Author, Year); they become links to the numbered reference. */
function linkCites(html, refs, href) {
  const find = (who, year) => {
    const first = who.replace(/\s+et al\.?$/, '').split(/\s*(?:&|and|и)\s*/)[0].trim();
    const f = first.toLowerCase();
    return refs.find((s) => s.year === year && s.names[0] && (s.names[0].toLowerCase() === f || s.names[0].toLowerCase().endsWith(' ' + f)));
  };
  html = html.replace(/\(([^()]*?\d{4}[a-z]?)\)/g, (all, inner) => {
    const parts = inner.split(/;\s*/);
    let hit = false;
    const out = parts.map((p) => {
      const m = p.match(/^(.*?)([A-ZÀ-Ž][\p{L}'’ -]*?(?:\s+et al\.|\s*&\s*[\p{L}'’ -]+?)?),\s*(\d{4})[a-z]?$/u);
      if (!m) return p;
      const s = find(m[2], m[3]);
      if (!s) return p;
      hit = true;
      return `${m[1]}<a class="cite" href="${href(s)}">${m[2]}, ${m[3]}</a>`;
    });
    return hit ? `(${out.join('; ')})` : all;
  });
  // narrative: Brooks (2014), Juslin & Laukka (2003), Rauscher et al. (1993)
  html = html.replace(/(?<![\p{L}>])((?:van der |de |di )?[A-ZÀ-Ž][\p{L}'’-]+(?:\s+et al\.|\s+(?:&|и)\s+[A-ZÀ-Ž][\p{L}'’-]+(?:\s[A-ZÀ-Ž][\p{L}'’-]+)?)?)\s\((\d{4})\)/gu, (all, who, year) => {
    const s = find(who, year);
    return s ? `<a class="cite" href="${href(s)}">${who} (${year})</a>` : all;
  });
  return html;
}

