/* Јаснота — the content flow: one topic → website → Instagram → Facebook.
   Requires render.js + refs.js + data.js + social.js (generated by tools/sync-social.mjs). Runs before pages.js.

   J.SOCIAL (the synced calendar) is the source of dates and of the `social` texts; J.POSTS (data.js) holds the
   designed carousels. This file joins them into J.FLOW, one entry per week:
     { key, week, date, pillar, fmt, title, title_en, slug, onSite, og, url, share{instagram,facebook},
       post (a J.POSTS item or null), fb (social.fb or null), ig (social.ig or null), placeholder }
   - a carousel whose calendar week moved (the launch article shifts the old 12 by +7 days) takes the calendar date
     and week number; its stories move with it;
   - a calendar week with `social.ig.slides` and no carousel in data.js becomes a carousel, rendered by the same
     templates (render.js → J.T): the data decides the words, never the layout;
   - until the launch topic is in the calendar, a placeholder week stands in for it.
   Nothing here fails when `social` is missing: the pages show what is still to come. */
(function () {
  'use strict';
  var J = window.J, esc = J.esc;
  var S = J.SOCIAL || { weeks: [], refs: {}, public_url: '', synced: '' };

  /* ---------------- references the synced calendar may cite (week 1) ---------------- */
  Object.keys(S.refs || {}).forEach(function (k) { if (!J.REFS[k]) J.REFS[k] = S.refs[k]; });

  /* ---------------- the order of a week ----------------
     web first (Mon morning), Instagram the same evening (Mon 19:30), Facebook the next evening (Tue 19:00):
     the article is live before any channel links to it, and Facebook reads its preview only after that. */
  J.PUBLIC_URL = (S.public_url || 'https://koalnix.github.io/jasnota/website/').replace(/\/?$/, '/');
  J.PUBLIC_HOST = J.PUBLIC_URL.replace(/^https?:\/\//, '').split('/')[0];
  J.WEB_TIME = '09:00';
  J.FB_OFFSET = 1;
  J.FB_TIME = '19:00';
  J.LAUNCH = { slug: 'rhythm-of-resilience', title: 'Ритамот на резилиентноста: како музиката ги обликува нашите емоции',
    title_en: 'The rhythm of resilience: how music shapes our emotions', date: '2026-11-02', pillar: 1 };

  /* …/articles/<slug>/?utm_source=instagram|facebook&utm_medium=social&utm_campaign=<slug> (same as website/tools/urls.mjs) */
  J.articleUrl = function (slug) { return J.PUBLIC_URL + 'articles/' + slug + '/'; };
  J.shareUrl = function (slug, source, campaign) {
    return J.articleUrl(slug) + '?utm_source=' + source + '&utm_medium=social&utm_campaign=' + encodeURIComponent(campaign || slug);
  };
  J.utm = function (url, source, campaign) {
    var q = 'utm_source=' + source + '&utm_medium=social&utm_campaign=' + encodeURIComponent(campaign);
    var h = url.indexOf('#'), hash = h > -1 ? url.slice(h) : '', base = h > -1 ? url.slice(0, h) : url;
    return base + (base.indexOf('?') > -1 ? '&' : '?') + q + hash;
  };
  J.fbDate = function (w) { return J.addDays(w.date, J.FB_OFFSET); };

  /* ---------------- match calendar weeks ↔ designed carousels ---------------- */
  function norm(s) { return J.strip(s || '').toLowerCase().replace(/[„“"'’‘«»:–—\-.,?!]/g, ' ').replace(/\s+/g, ' ').trim(); }
  var weeks = (S.weeks || []).slice().sort(function (a, b) { return a.date < b.date ? -1 : a.date > b.date ? 1 : a.week - b.week; });
  var taken = {};
  function matchPost(w) {
    var t = norm(w.title_mk), hit = null;
    var pid = w.social && w.social.ig && (w.social.ig.post_id || (!w.social.ig.slides && w.social.ig.id));
    if (pid) { hit = J.post(pid); if (hit && !taken[hit.id]) { taken[hit.id] = true; return hit; } hit = null; }
    J.POSTS.forEach(function (p) { if (!hit && !taken[p.id] && norm(p.title) === t) hit = p; });
    if (!hit && w.slug) J.POSTS.forEach(function (p) { if (!hit && !taken[p.id] && J.ARTICLES[p.id] === w.slug) hit = p; });
    if (hit) taken[hit.id] = true;
    return hit;
  }

  /* ---------------- a carousel from the calendar (social.ig) ---------------- */
  var NOTE = 'Ова не е дијагноза ни терапија.';
  function evKey(v) {
    if (!v) return undefined;
    v = String(v).toLowerCase();
    if (J.EV[v]) return v;
    return /^(сил|strong)/.test(v) ? 'strong' : /^(умер|moder)/.test(v) ? 'moderate' : /^(ран|early|огран|limit)/.test(v) ? 'early' : /^(отвор|open)/.test(v) ? 'open' : undefined;
  }
  function refIds(list, fallback) {
    var ids = (Array.isArray(list) ? list : []).filter(function (id) { return J.REFS[id]; });
    return ids.length ? ids : (fallback || []).filter(function (id) { return J.REFS[id]; });
  }
  function slideFrom(s, i, N, w) {
    if (typeof s === 'string') s = { text: s };
    var t = s.t || s.template || s.type || s.kind;
    var o;
    if (t && J.T[t]) { o = Object.assign({}, s, { t: t }); if (o.ev) o.ev = evKey(o.ev); if (t === 'sources') o.ids = refIds(o.ids, w.source_ids); return o; }
    var h = s.h || s.title || s.headline || s.heading || '';
    var p = s.p || s.body || s.text || s.copy || '';
    var ids = s.ids || s.source_ids || s.sources || s.refs;
    var c = s.c || s.cite || s.citations || s.source_ids;
    var ev = evKey(s.ev || s.evidence || s.evidence_label);
    var items = s.items || s.list || s.bullets;
    if (t === 'sources' || /^извори/i.test(J.strip(h)) || (i === N - 1 && Array.isArray(ids) && !p)) {
      return { t: 'sources', ids: refIds(ids, w.source_ids), eth: s.eth || s.note || NOTE, more: s.more || 'Целиот текст со сите извори: линкот во био' };
    }
    if (i === 0 || t === 'cover') return { t: 'cover-text', h: h || p, dek: s.dek || s.subtitle || s.sub || (h ? p : '') };
    if (s.known || s.unknown || t === 'known') return { t: 'known', known: s.known || [], unknown: s.unknown || [], help: s.help || s.note };
    if (s.num || s.number || s.stat) return { t: 'num', num: s.num || s.number || s.stat, h: h, p: p, ev: ev, c: c };
    if (Array.isArray(items)) return { t: 'list', h: h, items: items, ev: ev, c: c };
    return { t: 'text', h: h, p: p, ev: ev, c: c };
  }
  function tagsOf(x) {
    if (!x) return ['јаснота'];
    var a = Array.isArray(x) ? x : String(x).split(/[\s,]+/);
    return a.map(function (t) { return String(t).replace(/^#/, '').trim(); }).filter(Boolean);
  }
  function firstSentence(s) { var m = String(s || '').match(/^.+?[.!?](\s|$)/); return (m ? m[0] : String(s || '')).trim(); }
  function postFromCalendar(w) {
    var ig = w.social.ig, raw = ig.slides;
    var src = raw.map(function (s, i) { return slideFrom(s, i, raw.length, w); });
    if (!src.length || src[src.length - 1].t !== 'sources') src.push({ t: 'sources', ids: refIds(w.source_ids), eth: NOTE, more: 'Целиот текст со сите извори: линкот во био' });
    var id = ig.id || (w.week === 1 ? 'w00' : 'c' + J.pad(w.week));
    var srcIds = src[src.length - 1].ids || [];
    var first = srcIds[0];
    var p = {
      id: id, n: w.week, date: w.date, pillar: w.pillar || 1, fmt: J.FMT[w.fmt] ? w.fmt : 'text', web: !!w.slug, fromCalendar: true,
      title: w.title_mk, title_en: w.title_en || '',
      rq: '', why: w.slug === J.LAUNCH.slug ? 'The launch topic, rooted in Jasna’s workshop of the same name. The website article is the home; this carousel is the door to it.' : '',
      ethics: '', src: src,
      caption: { mk: ig.caption_mk || '', en: ig.summary_en || w.title_en || '' },
      tags: tagsOf(ig.hashtags),
      story: {
        tq: J.strip(w.title_mk).split(':')[0] + '<em>?</em>',
        source: first ? { id: first, line: firstSentence(J.REFS[first].finding || J.REFS[first].short), ev: undefined } : null,
        ask: { k: 'question', q: 'Што те интересира за музиката и <em>емоциите?</em>', note: 'ги читаме сите; објавуваме само со дозвола' }
      }
    };
    p.time = J.POST_TIME;
    J.compose(p);
    /* alt text written by the editor wins over the generated one */
    var alts = Array.isArray(ig.alt_mk) ? ig.alt_mk : null;
    p.slides.forEach(function (sl, k) {
      var own = (raw[k] && (raw[k].alt_mk || raw[k].alt)) || (alts && alts[k]);
      if (own) sl.alt = J.strip(own);
    });
    p.stories = J.STORY_SLOTS.map(function (slot) {
      var f;
      if (slot.kind === 'teaser') f = { k: 'teaser', post: p.id, q: p.story.tq };
      else if (slot.kind === 'share') f = { k: 'share', post: p.id, note: 'Нов карусел · ' + J.FMT[p.fmt].mk };
      else if (slot.kind === 'source') f = p.story.source ? { k: 'source', id: p.story.source.id, line: p.story.source.line } : null;
      else f = p.story.ask;
      return f ? { date: J.addDays(p.date, slot.off), time: slot.time, slot: slot.kind, label: slot.mk === 'интеракција' ? 'кутија за прашања' : slot.mk, f: f, post: p.id } : null;
    }).filter(Boolean);
    return p;
  }

  /* ---------------- build the flow ---------------- */
  var flow = [];
  weeks.forEach(function (w) {
    var social = w.social || {};
    var post = matchPost(w);
    var ig = social.ig || null;
    if (!post && ig && Array.isArray(ig.slides) && ig.slides.length) {
      try { post = postFromCalendar(w); J.POSTS.push(post); } catch (e) { if (window.console) console.warn('flow: week ' + w.week + ' carousel not rendered', e); post = null; }
    }
    if (post && post.date !== w.date) {            /* the calendar moved this week: carousel + stories follow */
      var shift = Math.round((J.date(w.date) - J.date(post.date)) / 864e5);
      post.date = w.date;
      (post.stories || []).forEach(function (s) { s.date = J.addDays(s.date, shift); });
    }
    if (post) post.n = w.week;
    var slug = w.slug || (post && J.ARTICLES[post.id]) || null;
    if (post && slug) J.ARTICLES[post.id] = slug;
    flow.push({
      key: post ? post.id : 'cal' + w.week, week: w.week, date: w.date, pillar: w.pillar || (post && post.pillar) || 1,
      fmt: (post && post.fmt) || w.fmt || 'text', title: w.title_mk || (post && post.title), title_en: w.title_en || (post && post.title_en) || '',
      slug: slug, onSite: !!w.on_site, og: w.og || null,
      url: slug ? J.articleUrl(slug) : null,
      share: slug ? { instagram: J.shareUrl(slug, 'instagram'), facebook: J.shareUrl(slug, 'facebook') } : null,
      post: post || null, fb: social.fb || null, ig: ig, placeholder: false
    });
  });
  /* carousels the calendar doesn't list (shouldn't happen): keep them, with their own dates */
  J.POSTS.forEach(function (p) {
    if (flow.some(function (f) { return f.post === p; })) return;
    var slug = J.ARTICLES[p.id] || null;
    flow.push({ key: p.id, week: p.n, date: p.date, pillar: p.pillar, fmt: p.fmt, title: p.title, title_en: p.title_en, slug: slug, onSite: false, og: null,
      url: slug ? J.articleUrl(slug) : null, share: slug ? { instagram: J.shareUrl(slug, 'instagram'), facebook: J.shareUrl(slug, 'facebook') } : null,
      post: p, fb: null, ig: null, placeholder: false });
  });
  /* the launch topic, until it is in the calendar */
  var hasLaunch = flow.some(function (f) { return f.slug === J.LAUNCH.slug || norm(f.title).indexOf('ритамот на резилиентноста') === 0; });
  if (!hasLaunch) {
    flow.push({ key: 'launch', week: 1, date: J.LAUNCH.date, pillar: J.LAUNCH.pillar, fmt: 'text', title: J.LAUNCH.title, title_en: J.LAUNCH.title_en,
      slug: null, onSite: false, og: null, url: null, share: null, post: null, fb: null, ig: null, placeholder: true });
  }
  flow.sort(function (a, b) { return a.date < b.date ? -1 : a.date > b.date ? 1 : (a.placeholder ? -1 : b.placeholder ? 1 : a.week - b.week); });
  J.POSTS.sort(function (a, b) { return a.date < b.date ? -1 : a.date > b.date ? 1 : a.n - b.n; });
  J.FLOW = flow;
  J.STATS.posts = J.POSTS.length;
  J.flowFor = function (post) { for (var i = 0; i < flow.length; i++) if (flow[i].post === post) return flow[i]; return null; };

  /* the warning, in one place */
  J.articleState = function (f) {
    if (f.onSite && f.slug) return { ok: true, mk: 'статијата е на веб' };
    return { ok: false, mk: 'статијата уште не е објавена — не објавувај на FB пред веб-текстот' };
  };
  J.fbLinkLabel = function (f) { return (f.fb && f.fb.link_label_mk) || 'Целиот текст со изворите:'; };
  /* FB text + the UTM link (a {link} placeholder in the text is replaced instead of appended) */
  J.fbText = function (f) {
    if (!f.fb || !f.fb.text_mk) return '';
    var link = f.share ? f.share.facebook : '[линк до статијата]';
    var t = String(f.fb.text_mk).trim();
    if (/\{link\}|\[линк\]/.test(t)) return t.replace(/\{link\}|\[линк\]/g, link);
    /* the link goes after the text and before a closing line of hashtags, if there is one */
    var paras = t.split(/\n\s*\n/), tags = /^#\S+(\s+#\S+)*$/.test(paras[paras.length - 1].trim()) ? paras.pop() : '';
    return paras.join('\n\n') + '\n\n' + J.fbLinkLabel(f) + ' ' + link + (tags ? '\n\n' + tags : '');
  };
  J.igCaption = function (f) {
    if (f.post) return J.publishedCaption(f.post);
    if (f.ig && f.ig.caption_mk) return f.ig.caption_mk + (f.ig.summary_en ? '\n\n' + J.DIVIDER + '\nEN: ' + f.ig.summary_en : '') + '\n\n' + tagsOf(f.ig.hashtags).map(function (t) { return '#' + t; }).join(' ');
    return '';
  };
  J.ogSrc = function (f) { return f.og ? J.root + f.og : J.root + 'website/assets/og/home.png'; };

  /* ---------------- counts in the static pages ---------------- */
  document.addEventListener('DOMContentLoaded', function () {
    var n = J.POSTS.length, first = J.POSTS[0], last = J.POSTS[n - 1];
    document.querySelectorAll('[data-nweeks]').forEach(function (el) { el.textContent = n + ' недели'; });
    document.querySelectorAll('[data-nposts]').forEach(function (el) { el.textContent = n; });
    if (first && last) document.querySelectorAll('[data-flow-range]').forEach(function (el) {
      el.textContent = J.longDate(first.date).replace(/ 2026$/, '') + ' – ' + J.longDate(last.date);
    });
    document.querySelectorAll('[data-synced]').forEach(function (el) {
      el.textContent = S.synced ? 'синхронизирано ' + S.synced + ' од ' + S.from : 'social.js не е синхронизиран';
    });
  });
})();
